"""Package the C1-C4 screen without publishing generated benchmark prose.

Usage: python collect_results.py /path/to/20261104-c14-strata-round
Run after the final controls and live validation finish. Timing data are inputs,
not regenerated by this script. Existing benchmark runners are archived with
their launch commands; their absolute paths describe the measured host.
"""

import argparse
import gzip
import hashlib
import json
import statistics
from pathlib import Path


def digest(data):
    return hashlib.sha256(data).hexdigest()


def scrub(value):
    if isinstance(value, list):
        return [scrub(item) for item in value]
    if isinstance(value, dict):
        return {
            key: scrub(item)
            for key, item in value.items()
            if key not in {"output_text", "api_key", "admin_api_key"}
        }
    return value


def load_runs(root, name):
    path = root / name / "results.jsonl"
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines()]


def summarize(runs):
    result = {}
    for concurrency in sorted({run["concurrency"] for run in runs}):
        group = [run for run in runs if run["concurrency"] == concurrency]
        good = [run for run in group if not run["errors"]]
        requests = [req for run in good for req in run["requests"]]
        verifications = sum(
            req["meta_info"].get("spec_verify_ct", 0) for req in requests
        )
        result[str(concurrency)] = {
            "successful_batches": len(good),
            "failed_batches": len(group) - len(good),
            "successful_requests": len(requests),
            "aggregate_e2e_tok_s": [run["output_tok_s"] for run in good],
            "mean_aggregate_e2e_tok_s": statistics.mean(
                run["output_tok_s"] for run in good
            )
            if good
            else None,
            "batch_median_decode_tok_s": [run["median_decode_tok_s"] for run in good],
            "output_tokens_per_verification": (
                sum(req["output_tokens"] for req in requests) / verifications
                if verifications
                else None
            ),
        }
    return result


def parity(baseline, candidate):
    """Compare matching first-repeat requests, including exact input hashes."""
    reference = {
        (run["concurrency"], req["case_id"]): req
        for run in baseline
        if run["repeat"] == 0 and not run["errors"]
        for req in run["requests"]
    }
    result = {}
    for run in candidate:
        if run["repeat"] != 0 or run["errors"]:
            continue
        matched = 0
        for req in run["requests"]:
            base = reference[(run["concurrency"], req["case_id"])]
            assert req["input_sha256"] == base["input_sha256"]
            assert req["output_tokens"] == base["output_tokens"]
            matched += req["output_sha256"] == base["output_sha256"]
        result[str(run["concurrency"])] = {
            "equal_output_hashes": matched,
            "compared": len(run["requests"]),
        }
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    root = args.source
    out = Path(__file__).resolve().parent
    raw = out / "raw"
    raw.mkdir(exist_ok=True)
    names = sorted(
        path.name
        for path in root.iterdir()
        if path.is_dir()
        and (path / "results.jsonl").exists()
        and path.name.startswith(
            ("baseline_", "compact_", "wide8_", "adaptive_", "post_")
        )
    )
    runs = {name: load_runs(root, name) for name in names}
    summary = {
        "baseline_commit": "23c879b38c6114ce3effd96baa052955b31dbcc1",
        "model": "RadixArk/Qwen3.8-Flash-Next-NVFP4",
        "model_revision": "7b719225242aacd3dbd3f9407468c2ee9a9d2594",
        "record_claim": False,
        "selected_office_profile": "v5.5 MTP-3/4, cap8; new flags off",
        "aggregation": "Arithmetic mean of per-batch aggregate rates; decode is per-stream, never summed",
        "runs": {name: summarize(data) for name, data in runs.items()},
        "first_repeat_output_parity": {},
    }
    for workload in ("code", "prose"):
        for variant in ("compact", "wide8", "adaptive", "adaptive_control", "post"):
            name = f"{variant}_{workload}"
            if name in runs:
                summary["first_repeat_output_parity"][name] = parity(
                    runs[f"baseline_{workload}"], runs[name]
                )
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")

    # Keep successful and failed screens. Full CUPTI traces and model tensors
    # stay on the host; hashes let a reviewer identify the original captures.
    paths = []
    for pattern in ("*.json", "*.jsonl", "*.log", "*.py", "prototypes/*"):
        paths.extend(root.glob(pattern))
    excluded = {"STATE.json", "WORK_NOTES.json", "upload_manifest.json"}
    paths = [path for path in paths if path.is_file() and path.name not in excluded]
    for name in names:
        for pattern in ("*.json", "*.jsonl"):
            paths.extend((root / name).glob(pattern))
    if (root / "live_images").exists():
        paths.extend((root / "live_images").glob("*.json*"))
    manifest = {}
    for path in sorted(set(paths)):
        original = path.read_bytes()
        data = original
        if path.suffix == ".json":
            data = (json.dumps(scrub(json.loads(data)), indent=2) + "\n").encode()
        elif path.suffix == ".jsonl":
            data = "".join(
                json.dumps(scrub(json.loads(line))) + "\n"
                for line in data.decode().splitlines()
            ).encode()
        relative = str(path.relative_to(root))
        dest = raw / (relative.replace("/", "_") + ".gz")
        archive = gzip.compress(data, mtime=0)
        dest.write_bytes(archive)
        manifest[dest.name] = {
            "source": relative,
            "source_sha256": digest(original),
            "archive_sha256": digest(archive),
            "sanitized": data != original,
        }
    metadata = {
        "hardware": "4x V100 SXM2 32GB, TP4, NVLink, 300W limits",
        "sampling": "temperature0, seed42, thinking off; fixed outputs except natural-EOS SPEED",
        "order": "Baseline, compact, wide8, adaptive, pristine adaptive control, restored baseline; reversed concurrency order in repeat2",
        "limitation": "Variants were sequential, not randomized interleaved A/B. Small differences are not established gains.",
        "raw_artifacts": manifest,
        "trace_hashes": {
            str(path.relative_to(root)): digest(path.read_bytes())
            for path in sorted(root.glob("*trace*/*.trace.json.gz"))
        },
    }
    (out / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(f"Packaged {len(manifest)} artifacts and {len(runs)} run groups")


if __name__ == "__main__":
    main()
